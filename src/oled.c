/*
 * SSD1309 facts used here (Solomon Systech SSD1309 datasheet Rev 1.1):
 *   - I2C address 0b011110x, x = SA0 (8.1.5).
 *   - After the address, a control byte: bit 7 Co, bit 6 D/C#, then six 0 bits. With
 *     Co = 0 the rest of the transfer is data bytes only; D/C# = 0 makes them commands,
 *     D/C# = 1 display RAM data (8.1.5.2). So 0x00 starts a command stream and 0x40 a RAM
 *     data stream.
 *   - RAM is 8 pages of 128 columns; each byte is one column of 8 pixels, bit 0 at the
 *     top (8.6).
 *   - Commands (Tables 9-1, 9-3, 9-4): FDh 12h unlock, AEh/AFh display off/on, 20h 00h
 *     horizontal addressing, 21h column range, 22h page range, A0h/A1h segment re-map,
 *     C0h/C8h COM scan direction.
 * Everything else (contrast, multiplex 64, display offset 0, clock, pre-charge, VCOMH,
 * COM pin configuration) is left at its reset value.
 */
#define ADDR_SA0_LOW  0x3Cu
#define ADDR_SA0_HIGH 0x3Du
#define CTRL_COMMANDS 0x00u
#define CTRL_DATA     0x40u

#define WIDTH       128u
#define PAGES       8u
#define CELL_WIDTH  6u
#define GLYPH_WIDTH 5u

static uint8_t frame[PAGES][WIDTH];
static uint8_t dirty; /* bit n set: page n changed since the last flush */
static uint8_t address;
static int present;

